// Builds src/data/catalog/fineli.generated.ts from the THL Fineli open data package.
//
//   node scripts/fineli/build-ingredients.mjs <path to unzipped Fineli_Rel20 folder>
//
// Only the Fineli foods that ingredients.ts links to are written, so the app
// carries a small table. Values are per 100 g of the edible part:
// energy (ENERC, kJ → kcal), protein (PROT), available carbohydrate (CHOAVL),
// fat (FAT), fibre (FIBC), sugars (SUGAR) and salt (NACL, mg → g), plus
// Fineli's special-diet flags (GLUTFREE, MILKFREE, VEGAN…), which tests use to
// cross-check the hand-set allergens.
//
// Fineli © Terveyden ja hyvinvoinnin laitos (THL), CC BY 4.0, https://fineli.fi
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { readFineli } from './read-fineli.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const dir = process.argv[2];
if (!dir) {
  console.error('Usage: node scripts/fineli/build-ingredients.mjs <Fineli folder>');
  process.exit(1);
}

const source = readFileSync(join(root, 'src/data/catalog/ingredients.ts'), 'utf8');
const ids = [...source.matchAll(/^\s*i\('[^']+',\s*'[^']*',\s*'[a-z]+',\s*(\d+),/gm)].map((m) => Number(m[1]));
const unique = [...new Set(ids)].sort((a, b) => a - b);

const foods = readFineli(dir);
const missing = unique.filter((id) => !foods.has(id));
if (missing.length) {
  console.error(`Unknown Fineli ids: ${missing.join(', ')}`);
  process.exit(1);
}

const lines = unique.map((id) => {
  const f = foods.get(id);
  const name = f.name.replace(/'/g, "\\'");
  return `  ${id}: { name: '${name}', kcal: ${f.kcal}, proteinG: ${f.proteinG}, carbsG: ${f.carbsG}, fatG: ${f.fatG}, fiberG: ${f.fiberG}, sugarG: ${f.sugarG}, saltG: ${f.saltG}, diets: [${f.diets.map((d) => `'${d}'`).join(', ')}] },`;
});

const out = `// GENERATED by scripts/fineli/build-ingredients.mjs. Do not edit by hand.
// Source: Fineli, Release 20. © Terveyden ja hyvinvoinnin laitos (THL), CC BY 4.0. https://fineli.fi
// Per 100 g of the edible part.

export type FineliFood = {
  name: string;
  kcal: number;
  proteinG: number;
  carbsG: number;
  fatG: number;
  fiberG: number;
  sugarG: number;
  saltG: number;
  /** Fineli special-diet flags, e.g. GLUTFREE, MILKFREE, EGGFREE, SOYAFREE, VEGAN, LACOVEGE, LACSFREE. */
  diets: readonly string[];
};

export const FINELI_RELEASE = 'Fineli Release 20';

export const FINELI: Readonly<Record<number, FineliFood>> = {
${lines.join('\n')}
};
`;
writeFileSync(join(root, 'src/data/catalog/fineli.generated.ts'), out);
console.log(`Wrote ${unique.length} Fineli foods for ${ids.length} ingredients.`);
