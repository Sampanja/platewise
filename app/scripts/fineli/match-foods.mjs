// Developer helper: proposes a Fineli food for every diary test food by name.
//
//   node scripts/fineli/match-foods.mjs <Fineli folder>            → prints proposals
//   node scripts/fineli/match-foods.mjs <Fineli folder> --write    → writes foodFineli.generated.ts
//
// The diary list (src/data/catalog/foods.ts) is a stand-in with rounded
// macros. Its vitamins and minerals come from the closest Fineli food: the
// match below, with hand overrides in OVERRIDES where the name match is poor.
// Fineli © THL, CC BY 4.0. https://fineli.fi
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { readFineli } from './read-fineli.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const [dir, flag] = process.argv.slice(2);

/** Food id → Fineli id where the name match is wrong or ambiguous (checked by hand). */
const OVERRIDES = JSON.parse(readFileSync(join(dirname(fileURLToPath(import.meta.url)), 'food-overrides.json'), 'utf8'));

const fold = (s) =>
  s
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/[^a-z0-9]+/g, ' ')
    .trim();

const text = readFileSync(join(root, 'src/data/catalog/text/fi/foods.ts'), 'utf8');
const foods = [...text.matchAll(/^\s*'?([a-z0-9-]+)'?: \{ name: '([^']+)'/gm)].map((m) => ({ id: m[1], name: m[2] }));
const fineli = [...readFineli(dir).values()];

function score(name, candidate) {
  const words = fold(name).split(' ').filter((w) => w.length > 1);
  const target = fold(candidate.name);
  const targetWords = target.split(' ');
  let hit = 0;
  for (const w of words) {
    if (targetWords.includes(w)) hit += 1;
    else if (targetWords.some((t) => t.startsWith(w.slice(0, Math.max(4, w.length - 2))))) hit += 0.7;
    else if (target.replace(/ /g, '').includes(w)) hit += 0.5;
  }
  // Prefer short, plain Fineli names (fewer extra words).
  return hit / words.length - targetWords.length * 0.01;
}

const out = [];
for (const food of foods) {
  const forced = OVERRIDES[food.id];
  let best = forced ? fineli.find((f) => f.id === forced) : null;
  let bestScore = forced ? 1 : -1;
  if (!best) {
    for (const candidate of fineli) {
      const s = score(food.name, candidate);
      if (s > bestScore) {
        bestScore = s;
        best = candidate;
      }
    }
  }
  out.push({ id: food.id, name: food.name, fineliId: best.id, fineliName: best.name, score: Math.round(bestScore * 100) / 100 });
}

if (flag !== '--write') {
  for (const row of out) console.log(`${row.score.toFixed(2)}\t${row.id}\t${row.name}\t→ ${row.fineliId} ${row.fineliName}`);
} else {
  const byId = new Map(fineli.map((f) => [f.id, f]));
  const lines = out.map((row) => {
    const f = byId.get(row.fineliId);
    return `  '${row.id}': [${row.fineliId}, ${f.satFatG}, ${f.vitDUg}, ${f.vitCMg}, ${f.b12Ug}, ${f.folateUg}, ${f.ironMg}, ${f.calciumMg}, ${f.potassiumMg}, ${f.magnesiumMg}, ${f.zincMg}], // ${f.name.replace(/\n/g, ' ')}`;
  });
  writeFileSync(
    join(root, 'src/data/catalog/foodFineli.generated.ts'),
    `// GENERATED by scripts/fineli/match-foods.mjs. Do not edit by hand.
// Source: Fineli, Release 20. © Terveyden ja hyvinvoinnin laitos (THL), CC BY 4.0. https://fineli.fi
// Diary test food → closest Fineli food and its vitamins and minerals per 100 g:
// [fineliId, satFatG, vitDUg, vitCMg, b12Ug, folateUg, ironMg, calciumMg, potassiumMg, magnesiumMg, zincMg]

export const FOOD_FINELI: Readonly<Record<string, readonly [number, number, number, number, number, number, number, number, number, number, number]>> = {
${lines.join('\n')}
};
`,
  );
  console.log(`Wrote ${lines.length} foods.`);
}
