/*
 * Writes src/features/widget/mascotSvgs.generated.ts: each character's idle
 * drawing as an SVG string for the Android home screen widget (which renders
 * SVG strings, not React Native views). Run after changing CharacterSvg.tsx:
 *
 *   npx jest --rootDir . --testMatch "**\/scripts/widget/*.gen.tsx"
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createElement, type ReactNode } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';

import { CharacterSvg } from '../../src/features/mascot/CharacterSvg';
import { CHARACTER_IDS } from '../../src/theme/characters';

jest.mock('react-native-svg', () => {
  const React = jest.requireActual('react');
  const KEEP_CASE = new Set(['cx', 'cy', 'rx', 'ry', 'fx', 'fy', 'viewBox']);
  const tag = (name: string) => {
    function El({ children, ...props }: { children?: ReactNode; [k: string]: unknown }) {
      const out: Record<string, unknown> = {};
      for (const [k, v] of Object.entries(props)) {
        if (k === 'accessible' || k === 'origin') continue;
        if (k === 'rotation') {
          out.transform = `rotate(${v} ${String(props.origin ?? '0, 0').replace(',', ' ')})`;
          continue;
        }
        out[KEEP_CASE.has(k) ? k : k.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`)] = v;
      }
      return React.createElement(name, out, children);
    }
    return El;
  };
  return {
    __esModule: true,
    default: tag('svg'),
    Circle: tag('circle'),
    Defs: tag('defs'),
    Ellipse: tag('ellipse'),
    G: tag('g'),
    Path: tag('path'),
    RadialGradient: tag('radialGradient'),
    Stop: tag('stop'),
  };
});

it('writes the widget mascots', () => {
  const lines = CHARACTER_IDS.map((id) => {
    const svg = renderToStaticMarkup(createElement(CharacterSvg, { character: id, state: 'happy', size: 200 }))
      .replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" ')
      // Standard SVG radial gradients have one radius (r), not rx/ry.
      .replace(/(<radialGradient[^>]*?) rx="([\d.]+%)" ry="[\d.]+%"/g, '$1 r="$2"');
    return `  ${id}: ${JSON.stringify(svg)},`;
  });
  writeFileSync(
    join(__dirname, '../../src/features/widget/mascotSvgs.generated.ts'),
    `// GENERATED by scripts/widget/generate-mascots.gen.tsx from CharacterSvg.tsx. Do not edit by hand.\n// The characters' happy pose as SVG strings for the Android home screen widget.\nimport type { CharacterId } from '@/theme/characters';\n\nexport const WIDGET_MASCOTS: Readonly<Record<CharacterId, string>> = {\n${lines.join('\n')}\n};\n`,
  );
});
