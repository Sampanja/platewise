/*
 * Writes src/features/widget/widgetArt.generated.ts: every character in the
 * moods the widget shows, and the quick action icons, as SVG strings (the
 * Android widget renders SVG strings, not React Native views). Run after
 * changing CharacterSvg.tsx or the icons:
 *
 *   npx jest --rootDir . --testMatch "**\/scripts/widget/*.gen.tsx"
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { createElement, type ReactNode } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';

import { CharacterSvg } from '../../src/features/mascot/CharacterSvg';
import { CHARACTER_IDS } from '../../src/theme/characters';

jest.mock('react-native-svg', () => {
  const React = jest.requireActual('react');
  const KEEP_CASE = new Set(['cx', 'cy', 'rx', 'ry', 'fx', 'fy', 'viewBox']);
  const tag = (name: string) => {
    function El({ children, ...props }: { children?: ReactNode; [k: string]: unknown }) {
      const out: Record<string, unknown> = {};
      for (const [k, v] of Object.entries(props)) {
        if (k === 'accessible' || k === 'origin' || k === 'importantForAccessibility' || k === 'testID') continue;
        if (k === 'rotation') {
          out.transform = `rotate(${v} ${String(props.origin ?? '0, 0').replace(',', ' ')})`;
          continue;
        }
        out[KEEP_CASE.has(k) ? k : k.replace(/[A-Z]/g, (m) => `-${m.toLowerCase()}`)] = v;
      }
      return React.createElement(name, out, children);
    }
    return El;
  };
  return {
    __esModule: true,
    default: tag('svg'),
    Svg: tag('svg'),
    Circle: tag('circle'),
    Defs: tag('defs'),
    Ellipse: tag('ellipse'),
    G: tag('g'),
    Line: tag('line'),
    Path: tag('path'),
    Polygon: tag('polygon'),
    Polyline: tag('polyline'),
    RadialGradient: tag('radialGradient'),
    Rect: tag('rect'),
    Stop: tag('stop'),
  };
});

/** Moods the widget shows (domain/mascotMood.ts). */
const MOODS = ['idle', 'happy', 'sleepy', 'encouraging', 'celebrating', 'cooking'] as const;
/** Replaced with the theme colour at render time. */
const ICON_COLOR = '#010203';
// The CommonJS build: Jest cannot load the package's ESM entry.
// eslint-disable-next-line @typescript-eslint/no-require-imports
const lucide = require(join(__dirname, '../../node_modules/lucide-react-native/dist/cjs/lucide-react-native.js')) as typeof import('lucide-react-native');
const ICONS = {
  camera: lucide.Camera,
  mic: lucide.Mic,
  barcode: lucide.Barcode,
  water: lucide.Droplet,
  plus: lucide.Plus,
  flame: lucide.Flame,
  target: lucide.Target,
  pot: lucide.CookingPot,
};

const svgOf = (element: ReturnType<typeof createElement>) =>
  renderToStaticMarkup(element)
    .replace(/ xmlns="[^"]*"/g, '')
    .replace(/ (class-name|aria-hidden)="[^"]*"/g, '')
    .replace('<svg ', '<svg xmlns="http://www.w3.org/2000/svg" ')
    // Standard SVG radial gradients have one radius (r), not rx/ry.
    .replace(/(<radialGradient[^>]*?) rx="([\d.]+%)" ry="[\d.]+%"/g, '$1 r="$2"');

it('writes the widget art', () => {
  const mascots = CHARACTER_IDS.map((id) => {
    const moods = MOODS.map((mood) => `    ${mood}: ${JSON.stringify(svgOf(createElement(CharacterSvg, { character: id, state: mood, size: 200 })))},`);
    return `  ${id}: {\n${moods.join('\n')}\n  },`;
  });
  const icons = Object.entries(ICONS).map(
    ([name, Icon]) => `  ${name}: ${JSON.stringify(svgOf(createElement(Icon, { size: 48, color: ICON_COLOR, strokeWidth: 2 })))},`,
  );
  writeFileSync(
    join(__dirname, '../../src/features/widget/widgetArt.generated.ts'),
    `// GENERATED by scripts/widget/generate-widget-art.gen.tsx from CharacterSvg.tsx and lucide icons. Do not edit by hand.
// SVG strings for the Android home screen widget.
import type { MoodState } from '@/domain/mascotMood';
import type { CharacterId } from '@/theme/characters';

export type WidgetMood = Exclude<MoodState, never>;

export const WIDGET_MASCOTS: Readonly<Record<CharacterId, Readonly<Record<WidgetMood, string>>>> = {
${mascots.join('\n')}
};

/** Icon colour placeholder; widgetIcon() swaps in the theme colour. */
export const WIDGET_ICON_COLOR = '${ICON_COLOR}';

export const WIDGET_ICONS = {
${icons.join('\n')}
} as const;

export type WidgetIconName = keyof typeof WIDGET_ICONS;
`,
  );
});
